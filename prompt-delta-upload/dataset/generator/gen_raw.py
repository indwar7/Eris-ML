#!/usr/bin/env python3
"""gen_raw.py - build the RAW dataset for "Prompt Edit Effect Attribution".

WHAT THIS DOES
--------------
Runs one open-weights instruction model (SmolLM2-1.7B-Instruct, Apache-2.0,
ungated) over a grid of

    prompt family  x  edit op  x  input slice  x  probe question

and records, for every cell, a NUMERIC BEHAVIOUR FINGERPRINT of the model's
responses. No response text is ever released: the released artifact is the
fingerprint, so a solver must reason about measured behaviour rather than
read the instruction back out of an answer.

The model is used only as an instrument. Nothing here is generated by an LLM
in the "LLM-authored content" sense: the prompt families, edit ops, slices
and probe questions are all written by hand in this file, and the recorded
numbers are measurements of a deterministic (greedy, do_sample=False) decode.

LICENCE
-------
Model weights: Apache-2.0 (HuggingFaceTB/SmolLM2-1.7B-Instruct), ungated.
Apache-2.0 governs the weights and code, not the text the model emits, and
this model's card places no claim or restriction on outputs. The recorded
measurements are therefore original derived work and are released CC0 1.0.

DETERMINISM
-----------
Greedy decoding, fixed seeds, fixed dtype, sorted iteration order. Running
this twice on the same hardware produces byte-identical output. Across
different GPUs the floating-point decode can differ marginally; the shipped
raw file is the authoritative artifact and prepare.py derives everything
from it.

USAGE
-----
    pip install torch transformers accelerate pandas numpy
    python gen_raw.py --out ../raw            # full build
    python gen_raw.py --out ../raw --smoke    # 2 families, quick check

On one A10G/T4/L4 the full build is roughly 1-2 hours.
"""

