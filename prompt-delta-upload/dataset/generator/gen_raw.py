# --------------------------------------------------------------------------
# FINGERPRINT - the released measurement. Deliberately numeric and
# behavioural. No response text is ever written out.
# --------------------------------------------------------------------------
BULLET_RE = re.compile(r"^\s*(?:[-*•]|\d+[.)])", re.M)
IDK_RE = re.compile(
    r"don't know|do not know|cannot|can't|unsure|uncertain|unable|"
    r"no way to know|depends", re.I)
REFUSE_RE = re.compile(
    r"i (?:can't|cannot|won't|will not)|not able to help|"
    r"against (?:policy|the law)|illegal|unethical|i'm sorry|i am sorry", re.I)
HEDGE_RE = re.compile(
    r"\b(?:might|may|could|perhaps|possibly|generally|typically|usually|"
    r"often|it depends|consider)\b", re.I)
FIRST_PERSON_RE = re.compile(r"\b(?:i|my|me|we|our)\b", re.I)
QUESTION_RE = re.compile(r"\?")


def fingerprint(text):
    """Map one response to a fixed-length numeric behaviour vector.

    Every component is a property of HOW the model answered, not of what the
    instruction said, so the vector cannot be inverted back to the prompt.
    """
    t = text.strip()
    words = t.split()
    n = len(words)
    sents = [s for s in re.split(r"[.!?]+", t) if s.strip()]
    uniq = len({w.lower().strip(".,!?;:") for w in words})
    return [
        float(n),                                        # length in words
        float(len(t)),                                   # length in chars
        float(len(sents)),                               # sentence count
        (n / len(sents)) if sents else 0.0,               # mean sentence length
        (uniq / n) if n else 0.0,                         # lexical diversity
        1.0 if t.startswith("{") or t.startswith("[") else 0.0,   # json-ish
        1.0 if BULLET_RE.search(t) else 0.0,              # list structure
        float(len(BULLET_RE.findall(t))),                 # how many bullets
        1.0 if IDK_RE.search(t) else 0.0,                 # admits ignorance
        1.0 if REFUSE_RE.search(t) else 0.0,              # refuses
        float(len(HEDGE_RE.findall(t))),                  # hedging density
        float(len(FIRST_PERSON_RE.findall(t))),           # first person
        float(len(QUESTION_RE.findall(t))),               # asks back
        float(sum(c.isdigit() for c in t)),               # digits used
        float(sum(c.isupper() for c in t)) / max(len(t), 1),      # caps ratio
        float(t.count("\n")),                             # line breaks
    ]


FP_NAMES = ["n_words", "n_chars", "n_sents", "mean_sent_len", "lex_div",
            "is_json", "has_bullets", "n_bullets", "says_idk", "refuses",
            "n_hedges", "n_first_person", "n_questions", "n_digits",
            "caps_ratio", "n_newlines"]


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="../raw")
    ap.add_argument("--model", default=MODEL_ID)
    ap.add_argument("--smoke", action="store_true",
                    help="2 families only, for a quick check")
    ap.add_argument("--batch", type=int, default=BATCH)
    args = ap.parse_args()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    random.seed(SEED)
    torch.manual_seed(SEED)

    dev = ("cuda" if torch.cuda.is_available()
           else "mps" if torch.backends.mps.is_available() else "cpu")
    dtype = torch.float16 if dev != "cpu" else torch.float32
    print(f"device={dev} dtype={dtype} model={args.model}")

    tok = AutoTokenizer.from_pretrained(args.model)
    tok.padding_side = "left"
    if tok.pad_token is None:
        tok.pad_token = tok.eos_token
    model = AutoModelForCausalLM.from_pretrained(
        args.model, dtype=dtype).to(dev).eval()

    families = FAMILIES[:2] if args.smoke else FAMILIES

    # Build the full job list first so batching is uniform and the iteration
    # order is fixed (determinism).
    jobs = []
    for fam in families:
        for op in sorted(OPS):
            for sl in SLICES:
                for qi, q in enumerate(fam["probes"][sl]):
                    prompt = OPS[op](fam["base"]) + "\n\n" + q
                    jobs.append((fam["family_id"], op, sl, qi, prompt))
    print(f"families={len(families)}  ops={len(OPS)}  slices={len(SLICES)}  "
          f"generations={len(jobs):,}")

    results = {}
    t0 = time.time()
    for i in range(0, len(jobs), args.batch):
        chunk = jobs[i:i + args.batch]
        texts = [tok.apply_chat_template(
                    [{"role": "user", "content": p}],
                    add_generation_prompt=True, tokenize=False)
                 for *_, p in chunk]
        enc = tok(texts, return_tensors="pt", padding=True,
                  add_special_tokens=False).to(dev)
        with torch.no_grad():
            gen = model.generate(**enc, max_new_tokens=MAX_NEW_TOKENS,
                                 do_sample=False,
                                 pad_token_id=tok.pad_token_id)
        cut = enc["input_ids"].shape[1]
        for (fid, op, sl, qi, _), row in zip(chunk, gen):
            txt = tok.decode(row[cut:], skip_special_tokens=True)
            results[f"{fid}|{op}|{sl}|{qi}"] = fingerprint(txt)
        done = i + len(chunk)
        if done % (args.batch * 20) == 0 or done == len(jobs):
            el = time.time() - t0
            print(f"  {done:,}/{len(jobs):,}  {el:6.0f}s  "
                  f"eta {el / done * (len(jobs) - done):6.0f}s", flush=True)

    payload = {
        "schema": 1,
        "model_id": args.model,
        "model_licence": "Apache-2.0 (weights); no restriction on outputs",
        "dataset_licence": "CC0-1.0",
        "seed": SEED,
        "max_new_tokens": MAX_NEW_TOKENS,
        "decoding": "greedy (do_sample=False)",
        "fingerprint_fields": FP_NAMES,
        "ops": sorted(OPS),
        "edit_ops": sorted(EDIT_OPS),
        "slices": SLICES,
        "families": [f["family_id"] for f in families],
        "probes_per_slice": len(families[0]["probes"]["factual"]),
        "n_generations": len(jobs),
        "responses": results,
    }
    fp_path = out / "fingerprints.json"
    fp_path.write_text(json.dumps(payload, indent=1, sort_keys=True))

    # ship the grid definition alongside, so the build is reproducible
    grid = {
        "families": families,
        "ops": {k: k for k in sorted(OPS)},
        "slices": SLICES,
    }
    (out / "grid.json").write_text(json.dumps(grid, indent=1, sort_keys=True))

    digest = hashlib.sha256(fp_path.read_bytes()).hexdigest()
    (out / "meta.json").write_text(json.dumps({
        "generated_by": "gen_raw.py",
        "seed": SEED,
        "model_id": args.model,
        "n_generations": len(jobs),
        "fingerprints_sha256": digest,
        "elapsed_seconds": round(time.time() - t0, 1),
        "device": dev,
    }, indent=1))
    print(f"\nwrote {fp_path}  ({len(results):,} fingerprints)")
    print(f"sha256 {digest}")
    print(f"elapsed {time.time() - t0:.0f}s")


if __name__ == "__main__":
    main()
